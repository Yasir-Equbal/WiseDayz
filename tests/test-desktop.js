'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const main = fs.readFileSync(path.join(root, 'main.js'), 'utf8');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
assert.equal(pkg.main, 'main.js');
assert.ok(pkg.scripts['dist:win'].includes('electron-builder'));
assert.equal(pkg.build.productName, 'wisedayZ');
assert.match(main, /contextIsolation:\s*true/);
assert.match(main, /nodeIntegration:\s*false/);
assert.match(main, /127\.0\.0\.1/);
assert.match(main, /wisedayz-local-db\.json/);
assert.match(main, /delete process\.env\.OPENAI_API_KEY/);
assert.match(app, /window\.DAYWISE_API_BASE/);
assert.match(app, /function sendChat\(\)/);
assert.doesNotMatch(app, /apiRequest\('\/api\/assistant\/chat'/);
console.log('Desktop packaging checks: 10 passed');
